static inline int32_t sat32(int64_t x)
{
    if (x > 2147483647LL) return 2147483647;
    if (x < -2147483648LL) return -2147483647 - 1;
    return static_cast<int32_t>(x);
}

static inline int32_t mul_q16(int32_t a, int32_t b)
{
    return sat32((static_cast<int64_t>(a) * static_cast<int64_t>(b)) >> 16);
}

static uint32_t run_nn_fixed()
{
    for (uint32_t i = 0; i < FEATURES; ++i) {
        int32_t d = kFeatureQ16[i] - kFeatureMeanQ16[i];
        gNormQ16[i] = mul_q16(d, kFeatureInvStdQ16[i]);
    }

    for (uint32_t h = 0; h < HIDDEN; ++h) {
        int64_t acc = static_cast<int64_t>(kB1Q16[h]) << 16;
        for (uint32_t i = 0; i < FEATURES; ++i)
            acc += static_cast<int64_t>(gNormQ16[i]) *
                   static_cast<int64_t>(kW1Q16[i * HIDDEN + h]);

        int32_t v = sat32(acc >> 16);
        gHiddenQ16[h] = (v > 0) ? v : 0;
    }

    for (uint32_t o = 0; o < CLASSES; ++o) {
        int64_t acc = static_cast<int64_t>(kB2Q16[o]) << 16;
        for (uint32_t h = 0; h < HIDDEN; ++h)
            acc += static_cast<int64_t>(gHiddenQ16[h]) *
                   static_cast<int64_t>(kW2Q16[h * CLASSES + o]);

        gLogitsQ16[o] = sat32(acc >> 16);
    }

    uint32_t best = 0;
    for (uint32_t o = 1; o < CLASSES; ++o)
        if (gLogitsQ16[o] > gLogitsQ16[best])
            best = o;

    return best;
}

