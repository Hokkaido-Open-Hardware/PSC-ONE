static uint32_t speech_isqrt64(uint64_t value)
{
    uint64_t op = value;
    uint64_t result = 0u;
    uint64_t one = 1ULL << 62;

    while (one > op) {
        one >>= 2;
    }

    while (one != 0u) {
        if (op >= result + one) {
            op -= result + one;
            result = (result >> 1) + one;
        } else {
            result >>= 1;
        }
        one >>= 2;
    }

    return (uint32_t)result;
}

static int32_t speech_log2_q16(uint64_t value)
{
    int exponent = 0;
    uint64_t temp;
    uint64_t mantissa_q24;
    uint32_t fraction;
    uint32_t index;
    uint32_t remainder;
    int32_t a;
    int32_t b;
    int32_t interp;

    if (value == 0u) {
        return 0;
    }

    temp = value;
    while ((temp >>= 1) != 0u) {
        ++exponent;
    }

    if (exponent >= 24) {
        mantissa_q24 = value >> (exponent - 24);
    } else {
        mantissa_q24 = value << (24 - exponent);
    }

    fraction = (uint32_t)(mantissa_q24 - (1ULL << 24));
    index = fraction >> 16;
    remainder = fraction & 0xffffu;

    a = speech_log2_mantissa_q16[index];
    b = speech_log2_mantissa_q16[index + 1u];

    interp = a + (int32_t)(
        ((int64_t)(b - a) * (int64_t)remainder) >> 16);

    return (exponent << 16) + interp;
}

static void speech_fft4096_q30(void)
{
    uint32_t j = 0u;

    for (uint32_t i = 1u; i < SPEECH_FFT_SIZE; ++i) {
        uint32_t bit = SPEECH_FFT_SIZE >> 1;

        while ((j & bit) != 0u) {
            j ^= bit;
            bit >>= 1;
        }

        j ^= bit;

        if (i < j) {
            int32_t temp = speech_fft_re[i];
            speech_fft_re[i] = speech_fft_re[j];
            speech_fft_re[j] = temp;

            temp = speech_fft_im[i];
            speech_fft_im[i] = speech_fft_im[j];
            speech_fft_im[j] = temp;
        }
    }

    for (uint32_t length = 2u;
         length <= SPEECH_FFT_SIZE;
         length <<= 1) {

        const uint32_t half = length >> 1;
        const uint32_t step = SPEECH_FFT_SIZE / length;

        for (uint32_t base = 0u;
             base < SPEECH_FFT_SIZE;
             base += length) {

            for (uint32_t k = 0u; k < half; ++k) {
                const uint32_t twiddle_index = k * step;
                const int32_t wr =
                    speech_twiddle_cos_q30[twiddle_index];
                const int32_t wi =
                    -speech_twiddle_sin_q30[twiddle_index];

                const uint32_t even = base + k;
                const uint32_t odd = even + half;

                const int32_t br = speech_fft_re[odd];
                const int32_t bi = speech_fft_im[odd];

                const int32_t tr = (int32_t)(
                    ((int64_t)wr * br - (int64_t)wi * bi) >> 30);

                const int32_t ti = (int32_t)(
                    ((int64_t)wr * bi + (int64_t)wi * br) >> 30);

                const int32_t ar = speech_fft_re[even];
                const int32_t ai = speech_fft_im[even];

                /*
                 * Scale every FFT stage by 1 bit.
                 * 12 stages => overall 1/4096.
                 */
                speech_fft_re[even] = (ar + tr) >> 1;
                speech_fft_im[even] = (ai + ti) >> 1;
                speech_fft_re[odd]  = (ar - tr) >> 1;
                speech_fft_im[odd]  = (ai - ti) >> 1;
            }
        }
    }
}

static int speech_center_active_q30(
    const int16_t *samples,
    uint32_t count)
{
    uint64_t max_energy = 0u;
    uint64_t threshold_energy;
    uint64_t minimum_energy;
    int32_t first_active = -1;
    int32_t last_active = -1;
    uint32_t active_start = 0u;
    uint32_t active_end = count;
    uint32_t active_length;

    if ((samples == NULL) || (count == 0u)) {
        return -1;
    }

    if (count < SPEECH_FRAME_SIZE) {
        return -1;
    }

    /*
     * Pass 1: maximum 20 ms frame energy.
     * sqrt(mean(x^2)) comparison can be done in squared-energy domain.
     */
    for (uint32_t start = 0u;
         start + SPEECH_FRAME_SIZE <= count;
         start += SPEECH_FRAME_HOP) {

        uint64_t energy = 0u;

        for (uint32_t i = 0u; i < SPEECH_FRAME_SIZE; ++i) {
            const int32_t sample = samples[start + i];
            energy += (uint64_t)((int64_t)sample * sample);
        }

        if (energy > max_energy) {
            max_energy = energy;
        }
    }

    /*
     * Python threshold:
     *   max(max_rms * 0.12, 0.003)
     *
     * Squared:
     *   max(max_energy * 0.0144,
     *       0.003^2 * 32768^2 * frame_size)
     */
    threshold_energy = speech_udiv64_u32(max_energy * 144u, 10000u);

    minimum_energy =
        (uint64_t)9664u * SPEECH_FRAME_SIZE;

    if (threshold_energy < minimum_energy) {
        threshold_energy = minimum_energy;
    }

    /* Pass 2: first/last active frame. */
    for (uint32_t start = 0u;
         start + SPEECH_FRAME_SIZE <= count;
         start += SPEECH_FRAME_HOP) {

        uint64_t energy = 0u;

        for (uint32_t i = 0u; i < SPEECH_FRAME_SIZE; ++i) {
            const int32_t sample = samples[start + i];
            energy += (uint64_t)((int64_t)sample * sample);
        }

        if (energy >= threshold_energy) {
            if (first_active < 0) {
                first_active = (int32_t)start;
            }
            last_active = (int32_t)start;
        }
    }

    if (first_active >= 0) {
        int32_t start =
            first_active - (int32_t)SPEECH_PAD_SAMPLES;

        uint32_t end =
            (uint32_t)last_active +
            SPEECH_FRAME_SIZE +
            SPEECH_PAD_SAMPLES;

        active_start = (start > 0) ? (uint32_t)start : 0u;
        active_end = (end < count) ? end : count;
    }

    active_length = active_end - active_start;

    if (active_length >= SPEECH_TARGET_SAMPLES) {
        uint32_t peak_index = 0u;
        int32_t peak_value = -1;
        int32_t crop_start;
        int32_t max_crop;

        for (uint32_t i = 0u; i < active_length; ++i) {
            int32_t value = samples[active_start + i];

            if (value < 0) {
                value = -value;
            }

            if (value > peak_value) {
                peak_value = value;
                peak_index = i;
            }
        }

        crop_start =
            (int32_t)peak_index -
            (int32_t)(SPEECH_TARGET_SAMPLES / 2u);

        if (crop_start < 0) {
            crop_start = 0;
        }

        max_crop =
            (int32_t)(active_length - SPEECH_TARGET_SAMPLES);

        if (crop_start > max_crop) {
            crop_start = max_crop;
        }

        const uint32_t source =
            active_start + (uint32_t)crop_start;

        for (uint32_t i = 0u;
             i < SPEECH_TARGET_SAMPLES;
             ++i) {
            speech_centered_q30[i] =
                (int32_t)samples[source + i] << 15;
        }

    } else {
        const uint32_t offset =
            (SPEECH_TARGET_SAMPLES - active_length) / 2u;

        for (uint32_t i = 0u;
             i < SPEECH_TARGET_SAMPLES;
             ++i) {
            speech_centered_q30[i] = 0;
        }

        for (uint32_t i = 0u; i < active_length; ++i) {
            speech_centered_q30[offset + i] =
                (int32_t)samples[active_start + i] << 15;
        }
    }

    /*
     * Peak normalize to 0.95, matching predict_keyword.py.
     */
    int32_t peak_q30 = 0;

    for (uint32_t i = 0u;
         i < SPEECH_TARGET_SAMPLES;
         ++i) {

        int32_t value = speech_centered_q30[i];

        if (value < 0) {
            value = -value;
        }

        if (value > peak_q30) {
            peak_q30 = value;
        }
    }

    if (peak_q30 > 0) {
        const int64_t target_q30 = 1020054733LL; /* round(0.95 * 2^30) */

        for (uint32_t i = 0u;
             i < SPEECH_TARGET_SAMPLES;
             ++i) {

            speech_centered_q30[i] = sat32_i64(
                speech_sdiv64_s32(
                    (int64_t)speech_centered_q30[i] *
                    target_q30,
                    peak_q30));
        }
    }

    return 0;
}


static uint32_t abs_s16(int16_t value)
{
    int32_t v = (int32_t)value;
    return (uint32_t)((v < 0) ? -v : v);
}

static int16_t sample24_to_s16(uint32_t raw)
{
    /*
     * Sign-extend the microphone's 24-bit two's-complement sample,
     * then match the gain used when creating the reference WAV files.
     *
     * Reference conversion:
     *   pcm16 = saturate_s16((sample24 >> 8) * 12)
     */
    int32_t sample = (int32_t)(raw & 0x00ffffffu);

    if ((sample & 0x00800000) != 0) {
        sample |= (int32_t)0xff000000u;
    }

    sample = (sample >> 8) * 12;

    if (sample > 32767) {
        sample = 32767;
    } else if (sample < -32768) {
        sample = -32768;
    }

    return (int16_t)sample;
}

static int detect_voice_range(
    const int16_t *samples,
    uint32_t count,
    uint32_t *voice_start,
    uint32_t *voice_end)
{
    uint32_t first = count;
    uint32_t last = 0u;
    uint32_t active_run = 0u;

    if ((samples == NULL) ||
        (voice_start == NULL) ||
        (voice_end == NULL) ||
        (count < DETECT_BLOCK_SIZE)) {
        return -1;
    }

    for (uint32_t base = 0u;
         base + DETECT_BLOCK_SIZE <= count;
         base += DETECT_BLOCK_SIZE) {

        uint32_t sum = 0u;

        for (uint32_t i = 0u; i < DETECT_BLOCK_SIZE; ++i) {
            sum += abs_s16(samples[base + i]);
        }

        const uint32_t average = sum / DETECT_BLOCK_SIZE;

        if (average >= VOICE_THRESHOLD) {
            ++active_run;

            if ((active_run == MIN_ACTIVE_BLOCKS) && (first == count)) {
                first = base -
                    (MIN_ACTIVE_BLOCKS - 1u) * DETECT_BLOCK_SIZE;
            }

            last = base + DETECT_BLOCK_SIZE;
        } else {
            active_run = 0u;
        }
    }

    if ((first == count) || (last <= first)) {
        return -1;
    }

    *voice_start = first;
    *voice_end = (last <= count) ? last : count;
    return 0;
}

/*
 * Python-compatible fixed-point feature extractor.
 *
 * voice_start / voice_end are retained in the function signature for
 * compatibility with the current caller, but Python-compatible centering
 * is recomputed from the full PCM buffer here.
 */
int speech_extract_features(
    const int16_t *samples,
    uint32_t count,
    uint32_t voice_start,
    uint32_t voice_end,
    int32_t features[SPEECH_FEATURE_COUNT])
{
    (void)voice_start;
    (void)voice_end;

    if ((samples == NULL) || (features == NULL) || (count == 0u)) {
        return -1;
    }

    if (speech_center_active_q30(samples, count) != 0) {
        return -1;
    }

    for (uint32_t region = 0u;
         region < SPEECH_FRAME_COUNT;
         ++region) {

        const uint32_t base =
            region * SPEECH_REGION_SIZE;

        int64_t sum = 0;

        for (uint32_t i = 0u;
             i < SPEECH_REGION_SIZE;
             ++i) {
            sum += speech_centered_q30[base + i];
        }

        const int32_t mean_q30 =
            (int32_t)speech_sdiv64_s32(
                sum,
                (int32_t)SPEECH_REGION_SIZE);

        for (uint32_t i = 0u;
             i < SPEECH_FFT_SIZE;
             ++i) {

            if (i < SPEECH_REGION_SIZE) {
                const int32_t centered =
                    speech_centered_q30[base + i] - mean_q30;

                speech_fft_re[i] = (int32_t)(
                    ((int64_t)centered *
                     speech_hann_q30[i]) >> 30);
            } else {
                speech_fft_re[i] = 0;
            }

            speech_fft_im[i] = 0;
        }

        speech_fft4096_q30();

        int32_t band_log_q16[SPEECH_BAND_COUNT];

        for (uint32_t band = 0u;
             band < SPEECH_BAND_COUNT;
             ++band) {

            uint64_t power_sum = 0u;

            for (uint32_t k = speech_band_start[band];
                 k < speech_band_end[band];
                 ++k) {

                const int64_t re = speech_fft_re[k];
                const int64_t im = speech_fft_im[k];

                power_sum +=
                    (uint64_t)(re * re + im * im);
            }

            const uint32_t bins =
                (uint32_t)(
                    speech_band_end[band] -
                    speech_band_start[band]);

            if (bins != 0u) {
                power_sum =
                    speech_udiv64_u32(
                        power_sum,
                        bins);
            }

            /*
             * FFT is scaled by 1/4096 and samples are Q30.
             *
             * original_float_power =
             *   fixed_power * 4096^2 / 2^60
             * = fixed_power / 2^36
             *
             * Therefore:
             *   log2(1 + original_power)
             * = log2(2^36 + fixed_power) - 36
             *
             * log2 vs natural log differs only by a constant factor,
             * which disappears in the following per-region standardization.
             */
            band_log_q16[band] =
                speech_log2_q16(
                    power_sum + (1ULL << 36)) -
                (36 << 16);
        }

        int64_t mean_sum = 0;

        for (uint32_t band = 0u;
             band < SPEECH_BAND_COUNT;
             ++band) {
            mean_sum += band_log_q16[band];
        }

        const int32_t band_mean_q16 =
            (int32_t)(mean_sum >> 4);

        uint64_t variance_sum = 0u;

        for (uint32_t band = 0u;
             band < SPEECH_BAND_COUNT;
             ++band) {

            const int64_t delta =
                (int64_t)band_log_q16[band] -
                band_mean_q16;

            variance_sum +=
                (uint64_t)(delta * delta);
        }

        uint32_t std_q16 =
            speech_isqrt64(
                variance_sum >> 4);

        if (std_q16 == 0u) {
            std_q16 = 1u;
        }

        for (uint32_t band = 0u;
             band < SPEECH_BAND_COUNT;
             ++band) {

            const int64_t numerator =
                ((int64_t)band_log_q16[band] -
                 band_mean_q16) << 16;

            features[
                region * SPEECH_BAND_COUNT + band] =
                sat32_i64(
                    speech_sdiv64_s32(
                        numerator,
                        (int32_t)std_q16));
        }
    }

    return 0;
}

static int32_t shift_round(int32_t value, uint8_t shift)
{
    if (shift == 0u) {
        return value;
    }

    if (shift >= 31u) {
        return (value < 0) ? -1 : 0;
    }

    const int32_t rounding = (int32_t)1 << (shift - 1u);
    return (value >= 0) ?
        ((value + rounding) >> shift) :
        -(((-value) + rounding) >> shift);
}

__attribute__((unused))
static void run_dense_network(
    const int32_t features[SPEECH_FEATURE_COUNT],
    int32_t scores[SPEECH_CLASS_COUNT])
{
    const speech_model_t *model = active_model;

    for (uint32_t h = 0u; h < SPEECH_HIDDEN_COUNT; ++h) {
        int32_t sum = model->dense1_bias[h];
        const uint32_t row = h * SPEECH_FEATURE_COUNT;

        for (uint32_t i = 0u; i < SPEECH_FEATURE_COUNT; ++i) {
            sum += (int32_t)features[i] *
                   (int32_t)model->dense1_weight[row + i];
        }

        sum = shift_round(sum, model->dense1_shift);
        speech_hidden[h] = (sum > 0) ? sum : 0;
    }

    for (uint32_t output = 0u; output < SPEECH_CLASS_COUNT; ++output) {
        int32_t sum = model->dense2_bias[output];
        const uint32_t row = output * SPEECH_HIDDEN_COUNT;

        for (uint32_t h = 0u; h < SPEECH_HIDDEN_COUNT; ++h) {
            sum += speech_hidden[h] *
                   (int32_t)model->dense2_weight[row + h];
        }

        scores[output] = shift_round(sum, model->dense2_shift);
    }
}

void speech_recognition_set_model(const speech_model_t *model)
{
    if ((model == NULL) ||
        (model->dense1_weight == NULL) ||
        (model->dense1_bias == NULL) ||
        (model->dense2_weight == NULL) ||
        (model->dense2_bias == NULL)) {
        active_model = &dummy_model;
        return;
    }

    active_model = model;
}

/*
 * Built-in trained classifier for Python-compatible Q16.16 features.
 */
__attribute__((unused))
static speech_class_t speech_classify_features_q16(
    const int32_t features_q16[SPEECH_FEATURE_COUNT],
    int32_t scores[SPEECH_CLASS_COUNT])
{
    uint32_t best = 0u;

    run_trained_network_q16(features_q16, scores);

    for (uint32_t i = 1u; i < SPEECH_CLASS_COUNT; ++i) {
        if (scores[i] > scores[best]) {
            best = i;
        }
    }

    return (speech_class_t)best;
}

uint32_t speech_record(int16_t *samples, uint32_t count)
{
    uint32_t read_count = 0u;

    if ((samples == NULL) || (count == 0u)) {
        return 0u;
    }

    /* Flush I2S RX FIFO, following mic_api.c convention. */
    PSC_I2S_ST = 0x01u;

    while (read_count < count) {
        uint32_t raw;

        if (mic_read_sample24(&raw) != 0) {
            break;
        }

        samples[read_count++] = sample24_to_s16(raw);
    }

    return read_count;
}

int speech_recognize_pcm(
    const int16_t *samples,
    uint32_t count,
    speech_result_t *result)
{
    uint32_t voice_start;
    uint32_t voice_end;

    if ((samples == NULL) || (result == NULL) || (count == 0u)) {
        return -1;
    }

    uint32_t feature_count = count;

    /*
     * Keep the runtime path identical to the passing bare-metal regression:
     * use the first 2 seconds (32000 samples at 16 kHz) for feature extraction.
     */
    if (feature_count > SPEECH_FEATURE_INPUT_SAMPLES) {
        feature_count = SPEECH_FEATURE_INPUT_SAMPLES;
    }

    if (detect_voice_range(
            samples,
            feature_count,
            &voice_start,
            &voice_end) != 0) {
        return -2;
    }

    if (speech_extract_features(
            samples,
            feature_count,
            voice_start,
            voice_end,
            speech_features) != 0) {
        return -3;
    }

    result->class_id =
        speech_classify_features_q16(
            speech_features,
            result->score);
    result->voice_start = voice_start;
    result->voice_end = voice_end;
    return 0;
}

const char *speech_class_name(speech_class_t class_id)
{
    switch (class_id) {
    case SPEECH_CLASS_UP:
        return "UP";
    case SPEECH_CLASS_DOWN:
        return "DOWN";
    case SPEECH_CLASS_UNKNOWN:
        return "UNKNOWN";
    default:
        return "ERROR";
    }
}

int32_t s_call_speech_recognition_api(void)
{
    speech_result_t result;

    s_printf("SPEECH RECORD START samples=%d\n",
             (int)SPEECH_RECORD_SAMPLES);

    const uint32_t count =
        speech_record(speech_pcm, SPEECH_RECORD_SAMPLES);

    s_printf("SPEECH RECORD END samples=%d\n", (int)count);

    if (count != SPEECH_RECORD_SAMPLES) {
        s_printf("SPEECH MIC ERROR count=%d\n", (int)count);
        return (int32_t)SPEECH_CLASS_ERROR;
    }

    const int status = speech_recognize_pcm(speech_pcm, count, &result);

    if (status != 0) {
        s_printf("SPEECH RECOGNITION ERROR=%d\n", status);
        return (int32_t)SPEECH_CLASS_ERROR;
    }

    s_printf("VOICE RANGE start=%d end=%d\n",
             (int)result.voice_start,
             (int)result.voice_end);
    s_printf("SCORE UP=%d DOWN=%d UNKNOWN=%d\n",
             (int)result.score[SPEECH_CLASS_UP],
             (int)result.score[SPEECH_CLASS_DOWN],
             (int)result.score[SPEECH_CLASS_UNKNOWN]);
    s_printf("SPEECH RESULT=%s\n", speech_class_name(result.class_id));

    return (int32_t)result.class_id;
}