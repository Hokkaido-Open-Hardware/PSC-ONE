/*
 * RV32 helper: 64-bit / 32-bit division without libgcc __divdi3/__udivdi3.
 * Shift/subtract implementation; divisor must be non-zero.
 */
static uint64_t speech_udiv64_u32(uint64_t numerator, uint32_t denominator)
{
    uint64_t quotient = 0u;
    uint64_t remainder = 0u;

    if (denominator == 0u) {
        return 0u;
    }

    for (int32_t bit = 63; bit >= 0; --bit) {
        remainder =
            (remainder << 1) |
            ((numerator >> (uint32_t)bit) & 1u);

        if (remainder >= (uint64_t)denominator) {
            remainder -= (uint64_t)denominator;
            quotient |= (1ULL << (uint32_t)bit);
        }
    }

    return quotient;
}

static int64_t speech_sdiv64_s32(int64_t numerator, int32_t denominator)
{
    uint64_t numerator_abs;
    uint32_t denominator_abs;
    uint64_t quotient;
    int negative = 0;

    if (denominator == 0) {
        return 0;
    }

    if (numerator < 0) {
        numerator_abs = (uint64_t)(-(numerator + 1)) + 1u;
        negative ^= 1;
    } else {
        numerator_abs = (uint64_t)numerator;
    }

    if (denominator < 0) {
        denominator_abs =
            (uint32_t)(-(int64_t)denominator);
        negative ^= 1;
    } else {
        denominator_abs = (uint32_t)denominator;
    }

    quotient =
        speech_udiv64_u32(
            numerator_abs,
            denominator_abs);

    if (negative != 0) {
        return -(int64_t)quotient;
    }

    return (int64_t)quotient;
}

static int32_t sat32_i64(int64_t value)
{
    if (value > 2147483647LL) return 2147483647;
    if (value < -2147483648LL) return (-2147483647 - 1);
    return (int32_t)value;
}

static int32_t mul_q16(int32_t a, int32_t b)
{
    return sat32_i64(((int64_t)a * (int64_t)b) >> 16);
}

static void run_trained_network_q16(
    const int32_t features_q16[SPEECH_FEATURE_COUNT],
    int32_t scores[SPEECH_CLASS_COUNT])
{
    for (uint32_t i = 0u; i < SPEECH_FEATURE_COUNT; ++i) {
        const int32_t centered =
            features_q16[i] - trained_feature_mean_q16[i];
        trained_norm_q16[i] =
            mul_q16(centered, trained_feature_inv_std_q16[i]);
    }

    for (uint32_t h = 0u; h < SPEECH_HIDDEN_COUNT; ++h) {
        int64_t acc = (int64_t)trained_b1_q16[h] << 16;
        for (uint32_t i = 0u; i < SPEECH_FEATURE_COUNT; ++i) {
            acc += (int64_t)trained_norm_q16[i] *
                   (int64_t)trained_w1_q16[
                       i * SPEECH_HIDDEN_COUNT + h];
        }
        const int32_t value = sat32_i64(acc >> 16);
        trained_hidden_q16[h] = (value > 0) ? value : 0;
    }

    for (uint32_t output = 0u; output < SPEECH_CLASS_COUNT; ++output) {
        int64_t acc = (int64_t)trained_b2_q16[output] << 16;
        for (uint32_t h = 0u; h < SPEECH_HIDDEN_COUNT; ++h) {
            acc += (int64_t)trained_hidden_q16[h] *
                   (int64_t)trained_w2_q16[
                       h * SPEECH_CLASS_COUNT + output];
        }
        scores[output] = sat32_i64(acc >> 16);
    }
}



